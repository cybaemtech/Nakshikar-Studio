/**
 * Retrieve the curated ALT tag for a given file path or image name.
 */
export function getAltTagForImage(filePathOrName: string, fallback = ""): string {
  if (!filePathOrName) return fallback;

  let norm = filePathOrName.replace(/\\/g, "/");
  try {
    norm = decodeURIComponent(norm);
  } catch (e) {
    // fallback if not URI encoded
  }

  const filename = norm.split("/").pop() || "";
  const nameWithoutExt = (filename.substring(0, filename.lastIndexOf(".")) || filename).toLowerCase().trim();
  
  // Try direct match
  if (IMAGE_ALT_TAGS[nameWithoutExt]) {
    return IMAGE_ALT_TAGS[nameWithoutExt];
  }

  // Try removing vite hash e.g. "hero-mural-BsW1_bCR" or "wall  1-XEB_a9Tp"
  const withoutHash = nameWithoutExt.replace(/-[a-z0-9_-]{8}$/i, "");
  if (IMAGE_ALT_TAGS[withoutHash]) {
    return IMAGE_ALT_TAGS[withoutHash];
  }

  // Try replacing underscore with comma / comma with underscore
  const commaVersion = withoutHash.replace(/_/g, ",");
  if (IMAGE_ALT_TAGS[commaVersion]) {
    return IMAGE_ALT_TAGS[commaVersion];
  }
  const underscoreVersion = withoutHash.replace(/,/g, "_");
  if (IMAGE_ALT_TAGS[underscoreVersion]) {
    return IMAGE_ALT_TAGS[underscoreVersion];
  }

  // Check matching by exact base key lookup
  for (const [key, alt] of Object.entries(IMAGE_ALT_TAGS)) {
    if (withoutHash === key || withoutHash.replace(/,/g, "_") === key.replace(/,/g, "_")) {
      return alt;
    }
  }

  // Substring match for unique long keys
  for (const [key, alt] of Object.entries(IMAGE_ALT_TAGS)) {
    if (key.length > 8 && (withoutHash.includes(key) || key.includes(withoutHash))) {
      return alt;
    }
  }

  return fallback || filename;
}
